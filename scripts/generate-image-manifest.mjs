#!/usr/bin/env node
/**
 * Scans public/images and writes lib/image-manifest.ts with intrinsic dimensions and a
 * tiny blur placeholder for every photograph. Run after adding or replacing images:
 *
 *   npm run photos:manifest
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "lib", "image-manifest.ts");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (exts.has(path.extname(entry.name).toLowerCase())) files.push(full);
  }
  return files.sort();
}

async function describe(file) {
  const image = sharp(file);
  const { width, height } = await image.metadata();
  const blur = await image
    .clone()
    .resize(14, undefined, { fit: "inside" })
    .webp({ quality: 40, alphaQuality: 40 })
    .toBuffer();
  return {
    width,
    height,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
  };
}

const files = await walk(imagesDir).catch(() => []);
const entries = [];
for (const file of files) {
  const publicPath = "/" + path.relative(path.join(root, "public"), file).split(path.sep).join("/");
  const meta = await describe(file);
  entries.push([publicPath, meta]);
}

const body = entries
  .map(
    ([src, m]) =>
      `  ${JSON.stringify(src)}: { width: ${m.width}, height: ${m.height}, blurDataURL:\n    ${JSON.stringify(m.blurDataURL)} },`
  )
  .join("\n");

const source = `// Generated by scripts/generate-image-manifest.mjs. Do not edit by hand.
export interface ImageMeta {
  width: number;
  height: number;
  blurDataURL: string;
}

export const imageManifest: Record<string, ImageMeta> = {
${body}
};
`;

await fs.writeFile(outFile, source);
console.log(`Wrote ${entries.length} entries to ${path.relative(root, outFile)}`);
